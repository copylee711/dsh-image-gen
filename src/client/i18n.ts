export type Translate = (key: MessageKey, vars?: Record<string, string | number>) => string

export function translator(lang: 'zh' | 'en'): Translate {
  const dict: Record<MessageKey, string> = lang === 'en' ? en : zh
  return (key, vars) => {
    let text = dict[key]
    if (vars !== undefined) for (const [name, value] of Object.entries(vars)) text = text.split(`{${name}}`).join(String(value))
    return text
  }
}

export function langOf(locale: LocaleService | undefined): 'zh' | 'en' {
  const active = locale?.getSnapshot()?.active ?? (typeof navigator === 'undefined' ? 'zh' : navigator.language)
  return active.toLowerCase().startsWith('zh') ? 'zh' : 'en'
}

/** Translator following DSH's language switch. */
export function useT(locale: LocaleService | undefined): Translate {
  const [lang, setLang] = useState(() => langOf(locale))
  useEffect(() => {
    if (locale === undefined) return
    return locale.subscribe(() => setLang(langOf(locale)))
  }, [locale])
  return translator(lang)
}
